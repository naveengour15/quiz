<?php

namespace App\Http\Controllers\SuperAdmin;

use App\Http\Controllers\Controller;
use App\Models\Quiz;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Validation\Rule;

class LoadTestController extends Controller
{
    /**
     * Show the load test form.
     */
    public function showForm()
    {
        return redirect()->route('superadmin.settings.index')->with('active_tab', 'load-test');
    }

    /**
     * Execute the load test command.
     */
    public function runTest(Request $request)
    {
        // Remove PHP max_execution_time limit for long-running tests
        ini_set('max_execution_time', '0');
        set_time_limit(0);

        $validated = $request->validate([
            'vus' => ['required', 'integer', 'min:1', 'max:10000'],
            'duration' => ['required', 'integer', 'min:5', 'max:600'],
            'quiz_id' => [
                'nullable',
                'string',
                'max:32',
                function ($attribute, $value, $fail) {
                    if (in_array($value, ['auto_normal', 'auto_fff'], true)) {
                        return;
                    }

                    if (! ctype_digit($value) || ! Quiz::whereKey($value)->exists()) {
                        $fail('Select a valid target quiz.');
                    }
                },
            ],
            'stages' => ['required', 'array', 'min:1'],
            'stages.*' => [
                'required',
                'string',
                Rule::in([
                    'join',
                    'waiting',
                    'start_counter',
                    'questions',
                    'sounds',
                    'answers',
                    'review_counter',
                    'answersheet',
                    'update_play_data',
                    'leaderboard',
                ]),
            ],
        ]);

        $vus = (int) $validated['vus'];
        $duration = (int) $validated['duration'];
        $quizId = $validated['quiz_id'] ?? null;
        $stagesStr = implode(',', $validated['stages']);

        $outputPath = storage_path('app/load-test-report.json');
        $output = '';
        $exitCode = 0;

        $artisanParams = [
            '--vus' => $vus,
            '--duration' => $duration,
            '--stages' => $stagesStr,
            '--output' => $outputPath,
        ];
        if (! empty($quizId)) {
            $artisanParams['--quiz_id'] = $quizId;
        }

        // Reuse the web request's initialized Laravel/database connection instead of
        // starting a second application process with a separate DB connection.
        $exitCode = Artisan::call('quiz:load-test', $artisanParams);
        $output = Artisan::output();

        $jsonExists = $exitCode === 0 && file_exists($outputPath);
        $downloadUrl = $jsonExists ? route('superadmin.load-test.report') : null;

        if ($request->ajax() || $request->wantsJson()) {
            return response()->json([
                'success' => $exitCode === 0,
                'output' => $output,
                'downloadUrl' => $downloadUrl,
            ], $exitCode === 0 ? 200 : 500);
        }

        return view('superadmin.load-test-result', [
            'output' => $output,
            'downloadUrl' => $downloadUrl,
            'success' => $exitCode === 0,
        ]);
    }

    /**
     * Download the private JSON report generated by the latest load test.
     */
    public function downloadReport()
    {
        $reportPath = storage_path('app/load-test-report.json');

        abort_unless(is_file($reportPath), 404, 'No load test report is available.');

        return response()->download($reportPath, 'load-test-report.json', [
            'Content-Type' => 'application/json',
        ]);
    }
}
